export function sanitizeProduct(p: ProductModel): ProductModel {
  if (!p) return p;
  
  let updated = { ...p };

  // 1. Direct ID overrides
  if (PRODUCT_IMAGE_OVERRIDES[p.id]) {
    updated.images = [...PRODUCT_IMAGE_OVERRIDES[p.id]];
  }

  // 2. Filter out known 404 / broken Unsplash images from any product
  if (Array.isArray(updated.images)) {
    updated.images = updated.images.filter(
      img => typeof img === 'string' && img.trim() !== '' && !KNOWN_BROKEN_IMAGE_IDS.some(badId => img.includes(badId))
    );
  }

  // Ensure all beauty items have strictly correct, unambiguous subcategories
  if (p.category_id === BEAUTY_CATEGORY_ID) {
    if (p.id === 'c601dc3b-f07e-4cd9-a122-b12d1fcf8924') {
      updated.subcategory = 'skincare';
    } else if (p.id === 'a89bc051-57a0-4816-a2ca-969748099da6') {
      updated.subcategory = 'skincare';
    } else if (!updated.subcategory) {
      const text = `${updated.name} ${updated.description || ''}`.toLowerCase();
      // Evaluate haircare before skincare so hair serums are never tagged as skincare
      if (/\b(shampoo|conditioner|hair|scalp|keratin|hair straightener|argan oil)\b/i.test(text)) {
        updated.subcategory = 'haircare';
      } else if (/\b(parfum|perfume|fragrance|eau de|toilette|cologne|edp|edt|sauvage|chanel n°5)\b/i.test(text)) {
        updated.subcategory = 'fragrances';
      } else if (/\b(body wash|body lotion|body scrub|bath|soak|soap|shower gel|sugar soap)\b/i.test(text)) {
        updated.subcategory = 'bath-body';
      } else if (/\b(lipstick|foundation|palette|brush|compact|eyeshadow|mascara|eyeliner|blush|nail color|nail polish|concealer|kajal)\b/i.test(text)) {
        updated.subcategory = 'makeup';
      } else {
        updated.subcategory = 'skincare';
      }
    }
  }

  // Ensure all sports & fitness items have strictly correct subcategories
  if (p.category_id === SPORTS_CATEGORY_ID) {
    if (!updated.subcategory) {
      const text = `${updated.name} ${updated.description || ''}`.toLowerCase();
      if (/\b(cricket|bat|ball|pads|wicket|stump|leather ball|kashmir willow|english willow)\b/i.test(text)) {
        updated.subcategory = 'cricket';
      } else if (/\b(badminton|shuttle|shuttlecock|racquet|racket|yonex|li-ning)\b/i.test(text)) {
        updated.subcategory = 'badminton';
      } else if (/\b(football|soccer|goal|shin guard|fifa)\b/i.test(text)) {
        updated.subcategory = 'football';
      } else if (/\b(gym|dumbbell|barbell|treadmill|elliptical|workout|whey|protein|muscle|kore|powermax|strauss|weight|resistance band)\b/i.test(text)) {
        updated.subcategory = 'fitness';
      } else if (/\b(cycling|bicycle|bike|helmet|saddle)\b/i.test(text)) {
        updated.subcategory = 'cycling';
      } else if (/\b(yoga|pilates|mat|stretch|foam roller)\b/i.test(text)) {
        updated.subcategory = 'yoga';
      } else if (/\b(swim|swimming|goggles|swim cap)\b/i.test(text)) {
        updated.subcategory = 'swimming';
      } else if (/\b(outdoor|hiking|trekking|tent|camp|camping|rucksack)\b/i.test(text)) {
        updated.subcategory = 'outdoor';
      } else {
        updated.subcategory = 'fitness';
      }
    }
  }

  // 3. If it's a fashion product, ensure its images NEVER contain phone photos
  if (p.category_id === FASHION_CATEGORY_ID) {
    const hasPhoneImage = updated.images?.some(img => PHONE_IMAGE_IDS.some(id => img.includes(id)));
    if (hasPhoneImage) {
      updated.images = [
        'https://images.unsplash.com/photo-1541099649105-f69ad21f3246?w=800&h=800&fit=crop&auto=format',
        'https://images.unsplash.com/photo-1541099649105-f69ad21f3246?w=800&h=800&fit=crop&auto=format',
      ];
    }
  }

  // 4. Guarantee every product has at least one valid image
  if (!updated.images || updated.images.length === 0) {
    const fallback = CATEGORY_FALLBACK_IMAGES[updated.category_id] || 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=800&h=800&fit=crop&auto=format';
    updated.images = [fallback, fallback];
  }

  // 5. Gender auto-inference if not explicitly set
  if (!updated.gender) {
    const text = `${updated.name} ${updated.description}`.toLowerCase();
    if (/\b(women|women's|womens|lady|ladies|female|girl|girls|saree|anarkali|kurti|dress|frock)\b/i.test(text)) {
      updated.gender = 'women';
    } else if (/\b(men|men's|mens|male|gent|gents)\b/i.test(text)) {
      updated.gender = 'men';
    } else if (/\b(kid|kids|boy|boys|infant|toddler)\b/i.test(text)) {
      updated.gender = 'kids';
    } else {
      updated.gender = 'unisex';
    }
  }

  return updated;
}

// Strict gender separation functions (prevent "women" from matching "men")
export function isMenProduct(p: ProductModel): boolean {
  if (p.gender === 'men') return true;
  if (p.gender === 'women' || p.gender === 'kids') return false;
  const name = (p.name || '').toLowerCase();
  const desc = (p.description || '').toLowerCase();
  const text = `${name} ${desc}`;
  // Crucial: If it contains any women-specific keywords, NEVER classify as men
  if (/\b(women|women's|womens|lady|ladies|female|girl|girls|saree|anarkali|kurti|dress|frock|bra)\b/i.test(text)) {
    return false;
  }
  return /\b(men|men's|mens|male|gent|gents)\b/i.test(text);
}

export function isWomenProduct(p: ProductModel): boolean {
  if (p.gender === 'women') return true;
  if (p.gender === 'men' || p.gender === 'kids') return false;
  const name = (p.name || '').toLowerCase();
  const desc = (p.description || '').toLowerCase();
  const text = `${name} ${desc}`;
  return /\b(women|women's|womens|lady|ladies|female|girl|girls|saree|anarkali|kurti|dress|frock)\b/i.test(text);
}

export function isKidsProduct(p: ProductModel): boolean {
  if (p.gender === 'kids') return true;
  const name = (p.name || '').toLowerCase();
  const desc = (p.description || '').toLowerCase();
  const text = `${name} ${desc}`;
  return /\b(kid|kids|boy|boys|girl|girls|infant|toddler|baby|children)\b/i.test(text);
}


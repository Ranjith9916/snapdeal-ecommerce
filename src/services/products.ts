export const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isValidUUID(id: string): boolean {
  return Boolean(id && UUID_REGEX.test(id));
}

export async function getProductById(id: string) {
  if (!id) return null;
  const cleanId = String(id).trim();

  // 1. Check supplemental catalog first (sports, beauty, fashion, watches, toys, etc.)
  const supplementItem = ALL_SUPPLEMENTAL_PRODUCTS.find(
    f => f.id === cleanId || String(f.id).toLowerCase() === cleanId.toLowerCase()
  );
  if (supplementItem) {
    return sanitizeProduct(supplementItem);
  }

  // 2. If valid UUID, query Supabase DB
  if (isValidUUID(cleanId)) {
    try {
      const { data, error } = await supabase.from('products').select('*').eq('id', cleanId).maybeSingle();
      if (error) {
        console.error('Error fetching product from Supabase:', error);
        return null;
      }
      return data ? sanitizeProduct(data as ProductModel) : null;
    } catch (err) {
      console.error('Exception fetching product:', err);
      return null;
    }
  }

  return null;
}


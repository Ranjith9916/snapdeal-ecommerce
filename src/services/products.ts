export async function getProducts(options?: { categoryId?: string; limit?: number; gender?: 'men' | 'women' | 'kids' }) {
  let query = supabase.from('products').select('*');
  
  if (options?.categoryId) {
    query = query.eq('category_id', options.categoryId);
  }
  
  if (options?.limit) {
    query = query.limit(options.limit);
  }
  
  const { data, error } = await query.order('created_at', { ascending: false });
  let dbProducts: ProductModel[] = [];
  if (error) {
    console.error('Error fetching products:', error);
  } else if (data) {
    dbProducts = (data as ProductModel[]).map(sanitizeProduct);
  }

  // Enrich with supplementary products for categories that need catalog depth
  let allProducts = dbProducts;
  const existingIds = new Set(dbProducts.map(p => p.id));
  
  if (options?.categoryId) {
    const matchingSupplements = ALL_SUPPLEMENTAL_PRODUCTS.filter(
      p => p.category_id === options.categoryId && !existingIds.has(p.id)
    );
    allProducts = [...dbProducts, ...matchingSupplements];
  } else {
    // Unconstrained global query
    const matchingSupplements = ALL_SUPPLEMENTAL_PRODUCTS.filter(p => !existingIds.has(p.id));
    allProducts = [...dbProducts, ...matchingSupplements];
  }

  // STRICT CATEGORY ISOLATION GUARANTEE:
  if (options?.categoryId) {
    allProducts = allProducts.filter(p => p.category_id === options.categoryId);
  }

  // STRICT GENDER FILTERING (if requested)
  if (options?.gender === 'men') {
    allProducts = allProducts.filter(isMenProduct);
  } else if (options?.gender === 'women') {
    allProducts = allProducts.filter(isWomenProduct);
  } else if (options?.gender === 'kids') {
    allProducts = allProducts.filter(isKidsProduct);
  }

  if (options?.limit && allProducts.length > options.limit) {
    return allProducts.slice(0, options.limit);
  }

  return allProducts;
}

export async function getDealsProducts(options?: { minDiscount?: number; categoryId?: string; limit?: number }) {
  const minDiscount = options?.minDiscount ?? 25;
  const all = await getProducts(options?.categoryId ? { categoryId: options.categoryId } : undefined);
  
  // Filter products with significant discount and valid deals
  let deals = all.filter(p => (p.discount || 0) >= minDiscount || (p.original_price > p.price));
  
  // Sort by highest discount first
  deals.sort((a, b) => (b.discount || 0) - (a.discount || 0));

  if (options?.limit) {
    return deals.slice(0, options.limit);
  }
  return deals;
}


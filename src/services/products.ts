export async function searchProducts(keyword: string, categoryId?: string) {
  const cleanKeyword = keyword.trim().toLowerCase();
  
  // 1. Fetch from Supabase
  let query = supabase.from('products').select('*');

  if (cleanKeyword) {
    query = query.or(`name.ilike.%${cleanKeyword}%,brand.ilike.%${cleanKeyword}%`);
  }
    
  if (categoryId) {
    query = query.eq('category_id', categoryId);
  }
    
  const { data, error } = await query.order('created_at', { ascending: false }).limit(50);
  let dbProducts: ProductModel[] = [];
  if (error) {
    console.error('Error searching products:', error);
  } else if (data) {
    dbProducts = (data as ProductModel[]).map(sanitizeProduct);
  }

  // 2. Search within supplemental catalog
  const existingIds = new Set(dbProducts.map(p => p.id));
  let matchingSupplements = ALL_SUPPLEMENTAL_PRODUCTS.filter(item => {
    if (existingIds.has(item.id)) return false;
    if (categoryId && item.category_id !== categoryId) return false;
    if (!cleanKeyword) return true;

    return (
      item.name.toLowerCase().includes(cleanKeyword) ||
      item.brand.toLowerCase().includes(cleanKeyword) ||
      item.description.toLowerCase().includes(cleanKeyword) ||
      (item.subcategory && item.subcategory.toLowerCase().includes(cleanKeyword))
    );
  });

  let combined = [...dbProducts, ...matchingSupplements];

  // STRICT CATEGORY ISOLATION:
  if (categoryId) {
    combined = combined.filter(p => p.category_id === categoryId);
  }

  // CRITICAL GENDER ISOLATION:
  // If keyword specifically asks for "men" or "men's", NEVER allow women's items to match!
  const isTargetingMen = /\b(men|men's|mens|male|gents?)\b/i.test(cleanKeyword) && !/\b(women|women's|womens|female|ladies|lady)\b/i.test(cleanKeyword);
  const isTargetingWomen = /\b(women|women's|womens|female|ladies|lady)\b/i.test(cleanKeyword);
  const isTargetingKids = /\b(kid|kids|children|boy|boys|girl|girls)\b/i.test(cleanKeyword);

  if (isTargetingMen) {
    combined = combined.filter(isMenProduct);
  } else if (isTargetingWomen) {
    combined = combined.filter(isWomenProduct);
  } else if (isTargetingKids) {
    combined = combined.filter(isKidsProduct);
  }

  return combined.slice(0, 50);
}


export async function addReview(userId: string, productId: string, rating: number, comment: string) {
  if (rating < 1 || rating > 5 || !Number.isInteger(rating)) {
    return { success: false, error: 'Rating must be an integer between 1 and 5.' };
  }
  const cleanComment = comment.trim();
  if (!cleanComment) {
    return { success: false, error: 'Review comment cannot be empty.' };
  }

  const { data, error } = await supabase
    .from('reviews')
    .insert({
      user_id: userId,
      product_id: productId,
      rating,
      comment: cleanComment
    })
    .select()
    .single();

  if (error) {
    if (error.message.includes('Users can insert review if purchased') || error.code === '42501') {
      return { success: false, error: 'You can only review products from orders that have been delivered.' };
    }
    if (error.code === '23505' || error.message.includes('unique')) {
      return { success: false, error: 'You have already reviewed this product.' };
    }
    return { success: false, error: error.message };
  }
  return { success: true, data };
}



